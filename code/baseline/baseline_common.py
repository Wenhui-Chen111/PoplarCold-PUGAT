# -*- coding: utf-8 -*-
"""Shared utilities for reviewer-facing baseline experiments.

Design goals
------------
1. Reuse the exact split_manifest.csv generated by Train_ColdPU.py.
2. Use the same X.npy node features for every feature-using baseline.
3. Use the same preprocessed coexpression/PPI edges and edge weights for graph baselines.
4. Evaluate on exactly: current held-out positives + true unlabeled genes.
5. Keep validation/test positives out of all supervised/pseudo-negative training pools.
6. Write auditable per-split metrics, selected hyperparameters and method metadata.

This module intentionally contains no model implementation. Each baseline lives in its
own file, as requested for the public GitHub release.
"""
from __future__ import annotations

import argparse
import hashlib
import itertools
import json
import math
import os
import random
from dataclasses import dataclass
from pathlib import Path
from typing import Any, Callable, Dict, Iterable, List, Mapping, Optional, Sequence, Tuple

import numpy as np
import pandas as pd
from sklearn.metrics import average_precision_score, roc_auc_score

KS_DEFAULT: Tuple[int, ...] = (50, 100, 200)


@dataclass(frozen=True)
class BaselineData:
    X: np.ndarray
    y: np.ndarray
    gene_ids: List[str]
    feature_names: List[str]
    coexp_edge_index: np.ndarray
    coexp_edge_weight: np.ndarray
    ppi_edge_index: np.ndarray
    ppi_edge_weight: np.ndarray
    data_dir: str
    input_sha256: Dict[str, str]

    @property
    def n_nodes(self) -> int:
        return int(self.X.shape[0])

    @property
    def true_unlabeled_mask(self) -> np.ndarray:
        return self.y == 0


@dataclass(frozen=True)
class SplitMasks:
    repeat: int
    split_seed: int
    train_pos: np.ndarray
    val_pos: np.ndarray
    test_pos: np.ndarray
    true_unlabeled: np.ndarray


def set_seed(seed: int) -> None:
    random.seed(seed)
    np.random.seed(seed)
    try:
        import torch
        torch.manual_seed(seed)
        torch.cuda.manual_seed_all(seed)
    except Exception:
        pass


def read_gene_ids(path: Path) -> List[str]:
    with open(path, "r", encoding="utf-8") as handle:
        return [line.strip() for line in handle if line.strip()]


def sha256_file(path: Path, chunk_size: int = 1024 * 1024) -> str:
    h = hashlib.sha256()
    with open(path, "rb") as handle:
        while True:
            chunk = handle.read(chunk_size)
            if not chunk:
                break
            h.update(chunk)
    return h.hexdigest()


def _load_edges(data_dir: Path, prefix: str) -> Tuple[np.ndarray, np.ndarray]:
    edge_path = data_dir / f"edges_{prefix}.npy"
    weight_path = data_dir / f"edges_{prefix}_weight.npy"
    if not edge_path.exists() or not weight_path.exists():
        raise FileNotFoundError(f"Missing graph files: {edge_path} / {weight_path}")
    edge_index = np.load(edge_path).astype(np.int64)
    edge_weight = np.load(weight_path).astype(np.float32)
    if edge_index.ndim != 2 or edge_index.shape[0] != 2:
        raise ValueError(f"{edge_path} must have shape [2, E], got {edge_index.shape}")
    if edge_weight.ndim != 1 or edge_weight.shape[0] != edge_index.shape[1]:
        raise ValueError(f"{weight_path} length does not match {edge_path}")
    return edge_index, edge_weight


def load_preprocessed_data(data_dir: str) -> BaselineData:
    """Load exactly the same preprocessed arrays consumed by Train_ColdPU.py."""
    d = Path(data_dir)
    required = [
        "X.npy", "y.npy", "gene_ids.txt",
        "edges_coexp.npy", "edges_coexp_weight.npy",
        "edges_ppi.npy", "edges_ppi_weight.npy",
    ]
    missing = [name for name in required if not (d / name).exists()]
    if missing:
        raise FileNotFoundError("Missing required files:\n" + "\n".join(missing))

    X = np.load(d / "X.npy").astype(np.float32)
    y = np.load(d / "y.npy").astype(np.int64)
    gene_ids = read_gene_ids(d / "gene_ids.txt")
    feature_names = (
        read_gene_ids(d / "feature_names.txt")
        if (d / "feature_names.txt").exists()
        else [f"x_{i}" for i in range(X.shape[1])]
    )
    coexp_e, coexp_w = _load_edges(d, "coexp")
    ppi_e, ppi_w = _load_edges(d, "ppi")

    if X.ndim != 2:
        raise ValueError(f"X.npy must be 2D, got {X.shape}")
    if y.ndim != 1 or y.shape[0] != X.shape[0]:
        raise ValueError(f"y.npy shape {y.shape} incompatible with X {X.shape}")
    if len(gene_ids) != X.shape[0]:
        raise ValueError("gene_ids.txt length does not match X.npy")
    if len(feature_names) != X.shape[1]:
        raise ValueError("feature_names.txt length does not match X.npy columns")
    if not set(np.unique(y)).issubset({0, 1}):
        raise ValueError("y.npy must contain only 0/1 labels")
    if len(set(gene_ids)) != len(gene_ids):
        raise ValueError("gene_ids.txt contains duplicate gene IDs")

    fingerprint_names = [
        "X.npy", "y.npy", "gene_ids.txt",
        "edges_coexp.npy", "edges_coexp_weight.npy",
        "edges_ppi.npy", "edges_ppi_weight.npy",
    ]
    if (d / "feature_names.txt").exists():
        fingerprint_names.append("feature_names.txt")
    input_sha256 = {name: sha256_file(d / name) for name in fingerprint_names}

    return BaselineData(
        X=X, y=y, gene_ids=gene_ids, feature_names=feature_names,
        coexp_edge_index=coexp_e, coexp_edge_weight=coexp_w,
        ppi_edge_index=ppi_e, ppi_edge_weight=ppi_w,
        data_dir=str(d.resolve()), input_sha256=input_sha256,
    )


def load_split_manifest(path: str, data: BaselineData, split_mode: str) -> pd.DataFrame:
    """Load and validate the exact manifest generated by the revised main model."""
    manifest = pd.read_csv(path)
    required = {"repeat", "split_seed", "gene_id", "partition"}
    missing = required - set(manifest.columns)
    if missing:
        raise ValueError(f"Split manifest missing columns: {sorted(missing)}")

    manifest = manifest.copy()
    manifest["repeat"] = pd.to_numeric(manifest["repeat"], errors="raise").astype(int)
    manifest["split_seed"] = pd.to_numeric(manifest["split_seed"], errors="raise").astype(int)
    manifest["gene_id"] = manifest["gene_id"].astype(str)
    manifest["partition"] = manifest["partition"].astype(str)

    valid_parts = {"train", "val", "test"}
    if not set(manifest["partition"]).issubset(valid_parts):
        raise ValueError("partition must contain only train/val/test")

    pos_genes = set(np.asarray(data.gene_ids, dtype=object)[data.y == 1].tolist())
    for repeat, sub in manifest.groupby("repeat", sort=True):
        if sub["gene_id"].duplicated().any():
            raise ValueError(f"Duplicate gene_id entries in repeat {repeat}")
        observed = set(sub["gene_id"].tolist())
        if observed != pos_genes:
            missing_pos = sorted(pos_genes - observed)[:10]
            extra = sorted(observed - pos_genes)[:10]
            raise ValueError(
                f"Manifest repeat {repeat} does not match y.npy positives; "
                f"missing={missing_pos}, extra={extra}"
            )
        if sub["split_seed"].nunique() != 1:
            raise ValueError(f"Repeat {repeat} has multiple split_seed values")
        for part in ("train", "val", "test"):
            if int((sub["partition"] == part).sum()) == 0:
                raise ValueError(f"Repeat {repeat} has empty {part} partition")

        if split_mode == "grouped":
            if "group_key" not in sub.columns:
                raise ValueError("Grouped manifest must contain group_key")
            nonempty = sub[sub["group_key"].fillna("").astype(str).str.strip().ne("")]
            leakage = nonempty.groupby("group_key")["partition"].nunique()
            leakage = leakage[leakage > 1]
            if len(leakage):
                raise ValueError(
                    f"Grouped split leakage in repeat {repeat}; examples={leakage.index.tolist()[:10]}"
                )

    manifest = manifest.sort_values(["repeat", "gene_id"]).reset_index(drop=True)
    manifest.attrs["source_path"] = str(Path(path).resolve())
    manifest.attrs["sha256"] = sha256_file(Path(path))
    return manifest


def masks_from_manifest_repeat(data: BaselineData, manifest_repeat: pd.DataFrame) -> SplitMasks:
    n = data.n_nodes
    node_to_idx = {g: i for i, g in enumerate(data.gene_ids)}
    train = np.zeros(n, dtype=bool)
    val = np.zeros(n, dtype=bool)
    test = np.zeros(n, dtype=bool)

    for row in manifest_repeat.itertuples(index=False):
        idx = node_to_idx[row.gene_id]
        if data.y[idx] != 1:
            raise ValueError(f"Manifest gene {row.gene_id} is not positive in y.npy")
        if row.partition == "train":
            train[idx] = True
        elif row.partition == "val":
            val[idx] = True
        elif row.partition == "test":
            test[idx] = True
        else:
            raise ValueError(f"Unknown partition: {row.partition}")

    if np.any(train & val) or np.any(train & test) or np.any(val & test):
        raise ValueError("Split masks overlap")
    known_pos = data.y == 1
    if not np.array_equal(train | val | test, known_pos):
        raise ValueError("Manifest partitions do not cover exactly all positive genes")

    return SplitMasks(
        repeat=int(manifest_repeat["repeat"].iloc[0]),
        split_seed=int(manifest_repeat["split_seed"].iloc[0]),
        train_pos=train,
        val_pos=val,
        test_pos=test,
        true_unlabeled=data.true_unlabeled_mask.copy(),
    )


def compute_ranking_metrics(
    scores: np.ndarray,
    eval_pos_mask: np.ndarray,
    unlabeled_mask: np.ndarray,
    ks: Sequence[int] = KS_DEFAULT,
) -> Dict[str, float]:
    """Exactly match the revised Train_ColdPU.py evaluation universe.

    candidate set = current held-out positives + true unlabeled genes.
    Known positives assigned to the other held-out partition are excluded.
    """
    scores = np.asarray(scores, dtype=float).reshape(-1)
    eval_pos = np.asarray(eval_pos_mask, dtype=bool).reshape(-1)
    unlabeled = np.asarray(unlabeled_mask, dtype=bool).reshape(-1)
    if not (scores.shape == eval_pos.shape == unlabeled.shape):
        raise ValueError("scores/eval_pos/unlabeled must have the same length")
    if np.any(eval_pos & unlabeled):
        raise ValueError("eval_pos_mask and unlabeled_mask must be disjoint")
    if np.any(~np.isfinite(scores)):
        raise ValueError("Scores contain NaN/inf")

    candidate_mask = eval_pos | unlabeled
    cand = np.where(candidate_mask)[0]
    if len(cand) == 0:
        out: Dict[str, float] = {"MRR": 0.0, "AUPRC": 0.0, "AUROC": 0.0}
        for k in ks:
            out.update({f"Hits@{k}": 0, f"Precision@{k}": 0.0,
                        f"Recall@{k}": 0.0, f"nDCG@{k}": 0.0})
        return out

    candidate_scores = scores[cand]
    ranked = cand[np.argsort(-candidate_scores, kind="mergesort")]
    hidden = set(np.where(eval_pos)[0].tolist())
    hits = np.fromiter((1 if idx in hidden else 0 for idx in ranked), dtype=np.int64)

    hit_positions = np.flatnonzero(hits)
    mrr = 0.0 if len(hit_positions) == 0 else 1.0 / float(hit_positions[0] + 1)
    result: Dict[str, float] = {"MRR": float(mrr)}

    n_hidden = max(1, len(hidden))
    for k in ks:
        top = hits[:k]
        hit_count = int(top.sum())
        discounts = np.log2(np.arange(2, len(top) + 2, dtype=float))
        dcg = float((top / discounts).sum()) if len(top) else 0.0
        ideal_len = min(len(hidden), k)
        if ideal_len > 0:
            ideal_discounts = np.log2(np.arange(2, ideal_len + 2, dtype=float))
            idcg = float((np.ones(ideal_len) / ideal_discounts).sum())
        else:
            idcg = 0.0
        result[f"Hits@{k}"] = hit_count
        result[f"Precision@{k}"] = hit_count / float(k)
        result[f"Recall@{k}"] = hit_count / float(n_hidden)
        result[f"nDCG@{k}"] = dcg / idcg if idcg > 0 else 0.0

    y_true = eval_pos[cand].astype(np.int64)
    result["AUPRC"] = float(average_precision_score(y_true, candidate_scores)) if y_true.sum() else 0.0
    if y_true.sum() and y_true.sum() < len(y_true):
        result["AUROC"] = float(roc_auc_score(y_true, candidate_scores))
    else:
        result["AUROC"] = 0.0
    return result


def validation_key(metrics: Mapping[str, float]) -> float:
    return 0.6 * float(metrics.get("nDCG@100", 0.0)) + 0.4 * float(metrics.get("Recall@100", 0.0))


def merge_weighted_networks(
    data: BaselineData,
    coexp_ratio: float = 0.5,
    ppi_ratio: float = 0.5,
) -> Tuple[np.ndarray, np.ndarray]:
    """Merge both source networks exactly as the revised main script does in merged mode."""
    a, b = float(coexp_ratio), float(ppi_ratio)
    if a < 0 or b < 0 or a + b <= 0:
        raise ValueError("Network ratios must be non-negative and not both zero")
    s = a + b
    a, b = a / s, b / s

    edge_index = np.concatenate([data.coexp_edge_index, data.ppi_edge_index], axis=1)
    edge_weight = np.concatenate([
        data.coexp_edge_weight * a,
        data.ppi_edge_weight * b,
    ]).astype(np.float32)
    frame = pd.DataFrame({
        "src": edge_index[0], "dst": edge_index[1], "weight": edge_weight
    })
    frame = frame.groupby(["src", "dst"], as_index=False)["weight"].sum()
    frame["weight"] = frame["weight"].clip(0.0, 1.0)
    return (
        frame[["src", "dst"]].to_numpy(dtype=np.int64).T,
        frame["weight"].to_numpy(dtype=np.float32),
    )


def symmetrize_edges(
    edge_index: np.ndarray,
    edge_weight: np.ndarray,
    n_nodes: int,
    remove_self_loops: bool = False,
) -> Tuple[np.ndarray, np.ndarray]:
    """Return a coalesced undirected weighted edge list."""
    src = np.concatenate([edge_index[0], edge_index[1]])
    dst = np.concatenate([edge_index[1], edge_index[0]])
    weight = np.concatenate([edge_weight, edge_weight]).astype(np.float64)
    frame = pd.DataFrame({"src": src, "dst": dst, "weight": weight})
    if remove_self_loops:
        frame = frame[frame["src"] != frame["dst"]]
    frame = frame.groupby(["src", "dst"], as_index=False)["weight"].max()
    if frame[["src", "dst"]].to_numpy().max(initial=-1) >= n_nodes:
        raise ValueError("Edge index exceeds number of nodes")
    return (
        frame[["src", "dst"]].to_numpy(dtype=np.int64).T,
        frame["weight"].to_numpy(dtype=np.float32),
    )


def parameter_grid(grid: Mapping[str, Sequence[Any]], max_trials: Optional[int] = None) -> List[Dict[str, Any]]:
    keys = list(grid.keys())
    configs = [dict(zip(keys, vals)) for vals in itertools.product(*(grid[k] for k in keys))]
    if max_trials is not None and max_trials > 0:
        configs = configs[:max_trials]
    return configs


def save_json(path: Path, payload: Mapping[str, Any]) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    with open(path, "w", encoding="utf-8") as handle:
        json.dump(payload, handle, ensure_ascii=False, indent=2, default=_json_default)


def _json_default(obj: Any) -> Any:
    if isinstance(obj, (np.integer,)):
        return int(obj)
    if isinstance(obj, (np.floating,)):
        return float(obj)
    if isinstance(obj, np.ndarray):
        return obj.tolist()
    raise TypeError(f"Object of type {type(obj).__name__} is not JSON serializable")


def summarize_per_split(
    df: pd.DataFrame,
    metric_cols: Sequence[str],
    *,
    bootstrap_reps: int = 10000,
    seed: int = 20261001,
) -> pd.DataFrame:
    """Mean, SD, bootstrap 95% CI and t-based 95% CI across split repeats."""
    try:
        from scipy.stats import t as student_t
    except Exception:
        student_t = None

    rows: List[Dict[str, Any]] = []
    for j, metric in enumerate(metric_cols):
        values = pd.to_numeric(df[metric], errors="coerce").dropna().to_numpy(dtype=float)
        n = len(values)
        mean = float(np.mean(values)) if n else np.nan
        sd = float(np.std(values, ddof=1)) if n > 1 else 0.0 if n == 1 else np.nan

        if n > 1 and student_t is not None:
            half = float(student_t.ppf(0.975, n - 1) * sd / math.sqrt(n))
            t_lo, t_hi = mean - half, mean + half
        else:
            t_lo = t_hi = mean

        if n > 1 and bootstrap_reps > 0:
            rng = np.random.default_rng(seed + j)
            boot_means = np.empty(bootstrap_reps, dtype=float)
            for b in range(bootstrap_reps):
                boot_means[b] = float(np.mean(rng.choice(values, size=n, replace=True)))
            boot_lo, boot_hi = np.quantile(boot_means, [0.025, 0.975]).tolist()
        else:
            boot_lo = boot_hi = mean

        rows.append({
            "metric": metric, "n": n, "mean": mean, "std": sd,
            "ci95_boot_low": float(boot_lo), "ci95_boot_high": float(boot_hi),
            "ci95_t_low": float(t_lo), "ci95_t_high": float(t_hi),
        })
    return pd.DataFrame(rows)


def run_repeated_baseline(
    *,
    data: BaselineData,
    manifest: pd.DataFrame,
    out_dir: str,
    method_name: str,
    method_spec: Mapping[str, Any],
    fit_score_fn: Callable[[BaselineData, SplitMasks, int], Tuple[np.ndarray, Mapping[str, Any], Mapping[str, Any]]],
    train_seed_base: int = 10042,
    ks: Sequence[int] = KS_DEFAULT,
    save_scores: bool = True,
) -> Tuple[pd.DataFrame, pd.DataFrame]:
    """Run one baseline over every manifest repeat and save reviewer-facing outputs."""
    out = Path(out_dir)
    out.mkdir(parents=True, exist_ok=True)
    save_json(out / "method_spec.json", dict(method_spec))
    save_json(out / "reproducibility_inputs.json", {
        "data_dir": data.data_dir,
        "input_sha256": data.input_sha256,
        "split_manifest": {
            "path": manifest.attrs.get("source_path"),
            "sha256": manifest.attrs.get("sha256"),
        },
        "shape_and_counts": {
            "n_nodes": data.n_nodes,
            "n_features": int(data.X.shape[1]),
            "n_known_positives": int((data.y == 1).sum()),
            "n_true_unlabeled": int((data.y == 0).sum()),
            "n_coexp_edges": int(data.coexp_edge_index.shape[1]),
            "n_ppi_edges": int(data.ppi_edge_index.shape[1]),
        },
    })

    metric_rows: List[Dict[str, Any]] = []
    config_rows: List[Dict[str, Any]] = []

    repeats = sorted(manifest["repeat"].unique().tolist())
    for repeat in repeats:
        sub = manifest.loc[manifest["repeat"] == repeat].copy()
        masks = masks_from_manifest_repeat(data, sub)
        train_seed = int(train_seed_base + repeat - 1)
        set_seed(train_seed)

        scores, selected_config, audit = fit_score_fn(data, masks, train_seed)
        scores = np.asarray(scores, dtype=float).reshape(-1)
        if scores.shape[0] != data.n_nodes:
            raise ValueError(f"{method_name}: returned {len(scores)} scores for {data.n_nodes} nodes")

        val_metrics = compute_ranking_metrics(scores, masks.val_pos, masks.true_unlabeled, ks=ks)
        test_metrics = compute_ranking_metrics(scores, masks.test_pos, masks.true_unlabeled, ks=ks)

        row: Dict[str, Any] = {
            "method": method_name,
            "repeat": repeat,
            "split_seed": masks.split_seed,
            "train_seed": train_seed,
            "n_train_pos": int(masks.train_pos.sum()),
            "n_val_pos": int(masks.val_pos.sum()),
            "n_test_pos": int(masks.test_pos.sum()),
            "n_true_unlabeled": int(masks.true_unlabeled.sum()),
            "val_key": validation_key(val_metrics),
        }
        row.update(test_metrics)
        metric_rows.append(row)

        cfg_row: Dict[str, Any] = {
            "method": method_name,
            "repeat": repeat,
            "split_seed": masks.split_seed,
            "train_seed": train_seed,
            "selected_config_json": json.dumps(dict(selected_config), ensure_ascii=False, sort_keys=True),
            "audit_json": json.dumps(dict(audit), ensure_ascii=False, sort_keys=True, default=_json_default),
        }
        config_rows.append(cfg_row)

        if save_scores:
            score_df = pd.DataFrame({
                "gene_id": data.gene_ids,
                "score": scores,
                "is_train_pos": masks.train_pos,
                "is_val_pos": masks.val_pos,
                "is_test_pos": masks.test_pos,
                "is_true_unlabeled": masks.true_unlabeled,
            })
            score_df.to_csv(out / f"scores_repeat_{repeat:02d}.csv", index=False)

        pd.DataFrame(metric_rows).to_csv(out / "per_split_metrics.csv", index=False)
        pd.DataFrame(config_rows).to_csv(out / "selected_hyperparameters.csv", index=False)

        print(
            f"[{method_name}] repeat={repeat:02d} split_seed={masks.split_seed} "
            f"nDCG@100={test_metrics.get('nDCG@100', 0.0):.4f} "
            f"Recall@100={test_metrics.get('Recall@100', 0.0):.4f} "
            f"AUPRC={test_metrics.get('AUPRC', 0.0):.4f} "
            f"AUROC={test_metrics.get('AUROC', 0.0):.4f}"
        )

    metrics_df = pd.DataFrame(metric_rows)
    configs_df = pd.DataFrame(config_rows)
    metrics_df.to_csv(out / "per_split_metrics.csv", index=False)
    configs_df.to_csv(out / "selected_hyperparameters.csv", index=False)

    metric_cols = [c for c in metrics_df.columns if c in {
        "MRR", "AUPRC", "AUROC",
        *[f"Hits@{k}" for k in ks],
        *[f"Precision@{k}" for k in ks],
        *[f"Recall@{k}" for k in ks],
        *[f"nDCG@{k}" for k in ks],
    }]
    summarize_per_split(metrics_df, metric_cols).to_csv(out / "summary_metrics.csv", index=False)
    return metrics_df, configs_df


def base_parser(description: str) -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(description=description)
    parser.add_argument("--data_dir", required=True, help="Revised preprocessed data directory")
    parser.add_argument("--split_manifest", required=True, help="Exact split_manifest.csv from Train_ColdPU.py")
    parser.add_argument("--split_mode", required=True, choices=["random", "grouped"])
    parser.add_argument("--out_dir", required=True)
    parser.add_argument("--train_seed_base", type=int, default=10042,
                        help="Matches revised main-model default: repeat r uses base+r-1")
    parser.add_argument("--no_save_scores", action="store_true",
                        help="Do not save one score CSV per repeat")
    return parser


def prepare_from_args(args: argparse.Namespace) -> Tuple[BaselineData, pd.DataFrame]:
    data = load_preprocessed_data(args.data_dir)
    manifest = load_split_manifest(args.split_manifest, data, args.split_mode)
    return data, manifest
